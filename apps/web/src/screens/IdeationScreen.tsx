import React, { useState, useEffect, useCallback } from 'react';
import { useLanguage } from '../context/LanguageContext';
import { useAuth } from '../context/AuthContext';
import { useToast } from '../context/ToastContext';
import { apiClient } from '../lib/api';
import { Button } from '../components/common/Button';
import { Badge } from '../components/common/Badge';
import { Dialog } from '../components/common/Dialog';
import { Input } from '../components/common/Input';
import { Skeleton } from '../components/common/Skeleton';
import { EmptyState } from '../components/common/EmptyState';
import { ErrorState } from '../components/common/ErrorState';
import {
  Sparkles,
  Plus,
  ArrowRight,
  AlertCircle,
  TrendingUp,
  ExternalLink,
} from 'lucide-react';

interface Idea {
  id: string;
  title: string;
  angle: string;
  pillar: string;
  audience: string[];
  evidence_refs?: any[];
  total_score?: number;
  novelty_score: number;
  relevance_score: number;
  effort_score: number;
  priority?: string;
  status: string;
}

export const IdeationScreen: React.FC = () => {
  const { t, language } = useLanguage();
  const { session, canEdit } = useAuth();
  const { showToast } = useToast();
  const isEn = language === 'en';

  const [ideas, setIdeas] = useState<Idea[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Research modal state
  const [modalOpen, setModalOpen] = useState(false);
  const [topic, setTopic] = useState('Agents IA autonomes et gouvernance en entreprise');
  const [targetCount, setTargetCount] = useState(3);
  const [researching, setResearching] = useState(false);
  const [researchStep, setResearchStep] = useState<string>('');
  const [degradedTavily, setDegradedTavily] = useState(false);

  // Generating draft state
  const [convertingId, setConvertingId] = useState<string | null>(null);

  const fetchIdeas = async () => {
    setLoading(true);
    setError(null);
    try {
      const data = await apiClient<Idea[]>(
        `/v1/ideas?workspace_id=${session?.workspace_id || 'ws_default'}`
      );
      const rawList = Array.isArray(data) ? data : [];
      // Deduplicate ideas by ID and title
      const seen = new Set<string>();
      const deduped = rawList.filter((item) => {
        const key = item.id || item.title;
        if (seen.has(key)) return false;
        seen.add(key);
        return true;
      });
      setIdeas(deduped);
    } catch (err: any) {
      setError(err.message || (isEn ? 'Failed to load ideas.' : 'Impossible de charger les idées.'));
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchIdeas();
  }, [session?.workspace_id]);

  const handleCloseModal = useCallback(() => {
    if (!researching) {
      setModalOpen(false);
    }
  }, [researching]);

  const handleLaunchResearch = async (e: React.FormEvent) => {
    e.preventDefault();
    if (researching) return; // Prevent double trigger on multiple clicks

    setResearching(true);
    setResearchStep(
      isEn
        ? 'Querying sources via Tavily / Local document base...'
        : 'Recherche de sources via Tavily / Base documentaire...'
    );
    setDegradedTavily(false);

    try {
      setTimeout(() => {
        setResearchStep(
          isEn
            ? 'Fact extraction and editorial scoring via LangGraph...'
            : 'Extraction des faits et scoring éditorial par LangGraph...'
        );
      }, 1500);

      await apiClient<any>('/v1/ideas/research', {
        method: 'POST',
        body: JSON.stringify({
          topic_or_brief: topic.trim(),
          target_count: Math.min(10, Math.max(1, Math.round(Number(targetCount) || 1))),
          workspace_id: session?.workspace_id || 'ws_default',
        }),
      });

      setModalOpen(false);
      showToast('success', isEn ? 'New ideas generated by LangGraph agent!' : 'Nouvelles idées générées par l’agent LangGraph !');
      await fetchIdeas();
    } catch (err: any) {
      if (err.message?.toLowerCase().includes('tavily') || err.status === 502) {
        setDegradedTavily(true);
      }
      showToast('error', `Erreur de recherche d'idées : ${err.message || 'Échec du workflow'}`);
    } finally {
      setResearching(false);
      setResearchStep('');
    }
  };

  const handleConvertToDraft = async (idea: Idea) => {
    setConvertingId(idea.id);
    try {
      // 1. Create Brief
      const briefRes = await apiClient<any>('/v1/briefs', {
        method: 'POST',
        body: JSON.stringify({
          workspace_id: session?.workspace_id || 'ws_default',
          objective: idea.title,
          idea_id: idea.id,
          platform_targets: ['linkedin', 'x'],
          requirements: { angle: idea.angle },
        }),
      });

      // 2. Generate Content Package and Variants
      await apiClient<any>('/v1/content/generate', {
        method: 'POST',
        body: JSON.stringify({
          brief_id: briefRes.id,
          workspace_id: session?.workspace_id || 'ws_default',
        }),
      });

      showToast(
        'success',
        isEn
          ? 'Draft generated by agents! Redirecting to HITL Review...'
          : 'Brouillon généré par les agents ! Redirection vers la Revue HITL...'
      );
      window.location.hash = '#inbox';
    } catch (err: any) {
      showToast('error', `Erreur de transformation en brouillon : ${err.message}`);
    } finally {
      setConvertingId(null);
    }
  };

  const formatScore = (val?: number): string => {
    if (val === undefined || val === null || isNaN(val)) return '0';
    // Normalize to 0-100 integer score: if legacy [0.0, 10.0], scale by 10
    const num = val <= 10.0 && val > 0 ? val * 10 : val;
    return Math.min(100, Math.max(0, Math.round(num))).toString();
  };

  const formatPercent = (val?: number): string => {
    if (val === undefined || val === null || isNaN(val)) return '0%';
    const num = val <= 1.0 && val > 0 ? val * 100 : (val <= 10.0 ? val * 10 : val);
    return `${Math.min(100, Math.max(0, Math.round(num)))}%`;
  };

  if (loading && ideas.length === 0) {
    return (
      <div className="space-y-6">
        <Skeleton className="h-10 w-48" />
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          <Skeleton className="h-64 w-full rounded-xl" />
          <Skeleton className="h-64 w-full rounded-xl" />
          <Skeleton className="h-64 w-full rounded-xl" />
        </div>
      </div>
    );
  }

  if (error && ideas.length === 0) {
    return <ErrorState message={error} onRetry={fetchIdeas} />;
  }

  return (
    <div className="space-y-6 w-full">
      {/* Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-border-default pb-4">
        <div>
          <h2 className="text-lg sm:text-xl font-bold text-txt-primary tracking-tight">
            {t.ideation.title}
          </h2>
          <p className="text-xs text-txt-muted mt-0.5">
            {isEn
              ? 'Continuous environmental monitoring and high-engagement scored ideas via autonomous agents.'
              : 'Veille continue et génération d’idées à fort engagement par agents autonomes.'}
          </p>
        </div>

        {canEdit && (
          <Button
            variant="primary"
            onClick={() => setModalOpen(true)}
            className="flex items-center gap-2 min-h-[44px]"
          >
            <Plus className="h-4 w-4" />
            <span>{t.ideation.new_search_btn}</span>
          </Button>
        )}
      </div>

      {/* Tavily / LLM status banner if degraded */}
      {degradedTavily && (
        <div className="rounded-xl border border-status-warning-border bg-status-warning-bg p-4 text-xs text-status-warning-text flex items-center gap-3">
          <AlertCircle className="h-5 w-5 shrink-0" />
          <div>
            <strong className="block font-semibold">
              {isEn ? 'Degraded Mode Active (Tavily external search offline)' : 'Mode Dégradé Actif (Tavily non configuré ou indisponible)'}
            </strong>
            <span>
              {isEn
                ? 'External web search is temporarily replaced by local document cache.'
                : 'La recherche web externe est temporairement remplacée par le cache documentaire local.'}
            </span>
          </div>
        </div>
      )}

      {/* Ideas Grid */}
      {ideas.length === 0 ? (
        <EmptyState
          title={t.ideation.empty_title}
          description={t.ideation.empty_desc}
          actionLabel={t.ideation.new_search_btn}
          onAction={() => setModalOpen(true)}
        />
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
          {ideas.map((idea) => {
            const isConverting = convertingId === idea.id;
            return (
              <div
                key={idea.id}
                className="flex flex-col justify-between rounded-xl border border-border-default bg-surface p-5 hover:border-border-hover transition-colors shadow-subtle"
              >
                <div>
                  <div className="flex items-center justify-between gap-2 mb-2.5">
                    <div className="flex items-center gap-1.5 flex-wrap">
                      <Badge variant="neutral" className="text-[10px]">
                        {idea.pillar || (isEn ? 'General' : 'Général')}
                      </Badge>
                      <span className="text-[10px] font-mono px-1.5 py-0.5 rounded border border-accent/20 bg-accent/5 text-accent">
                        {idea.evidence_refs && idea.evidence_refs.length > 0
                          ? (isEn ? `Sourced (${idea.evidence_refs.length} proofs)` : `Veille sourcée (${idea.evidence_refs.length} preuves)`)
                          : (isEn ? 'Agent research' : 'Recherche Agent')}
                      </span>
                    </div>
                    <div className="flex items-center gap-1 text-[11px] font-mono text-accent font-semibold">
                      <TrendingUp className="h-3.5 w-3.5" />
                      <span>{formatPercent(idea.relevance_score)}</span>
                    </div>
                  </div>

                  <h3 className="text-sm font-semibold text-txt-primary leading-snug mb-2 line-clamp-2">
                    {idea.title}
                  </h3>

                  <p className="text-xs text-txt-secondary mb-3 line-clamp-3 leading-relaxed">
                    {idea.angle}
                  </p>

                  {/* Audience tags */}
                  {(() => {
                    const rawAud: any = idea.audience;
                    const audList: string[] = Array.isArray(rawAud)
                      ? rawAud
                      : typeof rawAud === 'string' && rawAud.trim()
                      ? [rawAud.trim()]
                      : [];
                    if (audList.length === 0) return null;
                    return (
                      <div className="flex items-center gap-1.5 flex-wrap mb-3">
                        <span className="text-[10px] text-txt-muted uppercase font-mono">{isEn ? 'Target:' : 'Cible:'}</span>
                        {audList.slice(0, 2).map((aud, i) => (
                          <span key={i} className="text-[10px] bg-app px-1.5 py-0.5 rounded text-txt-secondary border border-border-subtle">
                            {String(aud)}
                          </span>
                        ))}
                      </div>
                    );
                  })()}

                  {/* Grounded Evidence refs */}
                  {Array.isArray(idea.evidence_refs) && idea.evidence_refs.length > 0 && (
                    <div className="space-y-1 py-2.5 border-t border-border-subtle mb-1">
                      <span className="text-[10px] font-mono text-txt-muted block uppercase tracking-wider">
                        {isEn ? 'Grounded Evidence' : 'Preuves et Ancrage'} ({idea.evidence_refs.length})
                      </span>
                      {idea.evidence_refs.slice(0, 2).map((ev: any, idx: number) => {
                        const claim = typeof ev === 'string' ? ev : (ev?.claim || ev?.text || ev?.fact || 'Fait vérifié');
                        const sourceUrl = typeof ev === 'object' && ev ? (ev.source_id || ev.url || ev.source_url) : null;
                        return (
                          <div key={idx} className="text-[11px] text-txt-secondary flex items-start gap-1.5 bg-app/30 p-1.5 rounded border border-border-subtle">
                            <span className="text-accent">•</span>
                            <span className="line-clamp-1 flex-1 text-txt-primary">{claim}</span>
                            {sourceUrl && String(sourceUrl).startsWith('http') && (
                              <a
                                href={String(sourceUrl)}
                                target="_blank"
                                rel="noreferrer noopener"
                                className="text-accent hover:underline shrink-0"
                                title={String(sourceUrl)}
                              >
                                <ExternalLink className="h-3 w-3" />
                              </a>
                            )}
                          </div>
                        );
                      })}
                    </div>
                  )}

                  {/* Scores breakdown normalized to 0-100 */}
                  <div className="grid grid-cols-3 gap-2 py-2.5 border-t border-b border-border-subtle text-xs">
                    <div>
                      <span className="text-txt-muted block text-[10px]">
                        {isEn ? 'Novelty' : 'Nouveauté'}
                      </span>
                      <span className="font-semibold text-status-success-text text-xs">
                        {formatScore(idea.novelty_score)} / 100
                      </span>
                    </div>
                    <div>
                      <span className="text-txt-muted block text-[10px]">
                        {isEn ? 'Relevance' : 'Pertinence'}
                      </span>
                      <span className="font-semibold text-accent text-xs">
                        {formatScore(idea.relevance_score)} / 100
                      </span>
                    </div>
                    <div>
                      <span className="text-txt-muted block text-[10px]">
                        {isEn ? 'Effort' : 'Effort'}
                      </span>
                      <span className="font-semibold text-txt-secondary text-xs">
                        {formatScore(idea.effort_score)} / 100
                      </span>
                    </div>
                  </div>
                </div>

                <div className="pt-4 flex items-center justify-between gap-2">
                  <Button
                    variant="primary"
                    size="sm"
                    disabled={isConverting || !canEdit}
                    isLoading={isConverting}
                    onClick={() => handleConvertToDraft(idea)}
                    className="flex-1 justify-center text-xs min-h-[44px]"
                  >
                    <span>{isConverting ? (isEn ? 'Generating draft...' : 'Génération du brouillon...') : t.ideation.action_convert_draft}</span>
                    <ArrowRight className="h-3.5 w-3.5 ml-1" />
                  </Button>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Accessible Research Modal Dialog */}
      <Dialog
        isOpen={modalOpen}
        onClose={handleCloseModal}
        title={t.ideation.search_modal_title}
      >
        <form onSubmit={handleLaunchResearch} className="space-y-4">
          <div>
            <label
              htmlFor="research-topic"
              className="block text-xs font-semibold text-txt-secondary mb-1.5"
            >
              {isEn ? 'Theme or Editorial Trigger' : 'Thématique ou Déclencheur Éditorial'}
            </label>
            <Input
              id="research-topic"
              value={topic}
              onChange={(e) => setTopic(e.target.value)}
              placeholder={isEn ? 'e.g., Reasoning LLMs in Enterprise' : 'Ex: Architectures de modèles de raisonnement'}
              required
              disabled={researching}
              autoFocus
            />
          </div>

          <div>
            <label
              htmlFor="target-count"
              className="block text-xs font-semibold text-txt-secondary mb-1.5"
            >
              {isEn ? 'Target Ideas Count (1 to 10)' : 'Nombre d’idées cibles (1 à 10)'}
            </label>
            <Input
              id="target-count"
              type="number"
              min={1}
              max={10}
              step={1}
              value={targetCount}
              onChange={(e) => {
                const val = parseInt(e.target.value, 10);
                if (isNaN(val)) {
                  setTargetCount(1);
                } else {
                  setTargetCount(Math.min(10, Math.max(1, val)));
                }
              }}
              disabled={researching}
            />
          </div>

          {researching && (
            <div className="rounded-lg bg-surface-subtle p-3 text-xs text-accent-text flex items-center gap-2 border border-border-subtle">
              <Sparkles className="h-4 w-4 animate-spin shrink-0 text-accent" />
              <span>{researchStep || t.ideation.generating}</span>
            </div>
          )}

          <div className="flex justify-end gap-2.5 pt-3 border-t border-border-subtle">
            <Button
              type="button"
              variant="ghost"
              onClick={() => setModalOpen(false)}
              disabled={researching}
            >
              {isEn ? 'Cancel' : 'Annuler'}
            </Button>
            <Button
              type="submit"
              variant="primary"
              isLoading={researching}
            >
              {t.ideation.launch_research_btn}
            </Button>
          </div>
        </form>
      </Dialog>
    </div>
  );
};
